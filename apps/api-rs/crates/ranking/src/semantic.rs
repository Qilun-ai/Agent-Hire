//! Semantic similarity against a scoped vector snapshot or local profile rows.

use std::collections::BTreeSet;
use std::sync::Arc;

use agent_hire_ml::{self as ml, Embedder, EmbeddingMode, MINILM_DIMENSIONS};
use serde::Serialize;
use serde_json::{Map, Value, json};

use crate::{json_fields, profile_rows};

/// Identifies the profile entity represented by a stored vector.
#[derive(Clone, Copy, Debug, PartialEq, Eq, PartialOrd, Ord)]
#[non_exhaustive]
pub enum VectorKind {
    /// A profile skill.
    Skill,
    /// A project entry.
    Project,
    /// A work experience entry.
    Experience,
    /// An education, certification, award or achievement entry.
    Credential,
    /// A profile summary.
    Profile,
}

impl VectorKind {
    const ALL: [Self; 5] = [
        Self::Skill,
        Self::Project,
        Self::Experience,
        Self::Credential,
        Self::Profile,
    ];

    const fn index(self) -> usize {
        match self {
            Self::Skill => 0,
            Self::Project => 1,
            Self::Experience => 2,
            Self::Credential => 3,
            Self::Profile => 4,
        }
    }
}

/// A vector read by the caller from profile storage.
#[derive(Clone, Debug)]
pub struct ProfileVector {
    /// Stable profile row ID.
    pub id: String,
    /// The entity represented by this row.
    pub kind: VectorKind,
    /// Human-readable evidence label.
    pub label: String,
    /// Stored embedding coordinates.
    pub vector: Vec<f32>,
}

/// A set of stored rows generated by the same provider.
#[derive(Debug)]
pub struct ProfileVectors {
    /// Provider that generated these rows.
    pub mode: EmbeddingMode,
    /// Stored vectors the service may match against.
    pub rows: Vec<ProfileVector>,
}

/// Embedding resources to use for scoring. Defaults to the local hash rubric.
#[derive(Clone, Default)]
pub struct ScoringContext {
    /// Provider for real field similarity and stored-vector queries.
    pub embedder: Option<Embedder>,
    /// Optional caller-supplied snapshot of stored profile rows.
    pub vectors: Option<Arc<ProfileVectors>>,
}

/// One matching profile entity. Serializes as `[label, similarity]`.
#[derive(Clone, Debug, PartialEq)]
pub struct SemanticMatch {
    /// Human-readable evidence label.
    pub label: String,
    /// The 0–1 similarity.
    pub similarity: f64,
}

impl Serialize for SemanticMatch {
    fn serialize<S>(&self, serializer: S) -> Result<S::Ok, S::Error>
    where
        S: serde::Serializer,
    {
        (&self.label, self.similarity).serialize(serializer)
    }
}

/// Semantic score with evidence by profile group.
#[derive(Clone, Debug, PartialEq, Serialize)]
pub struct SemanticFit {
    /// Stretched similarity on the 0–100 scale.
    pub score: i64,
    /// Top skill evidence.
    pub skill_matches: Vec<SemanticMatch>,
    /// Top project evidence.
    pub project_matches: Vec<SemanticMatch>,
    /// Top work-experience evidence.
    pub experience_matches: Vec<SemanticMatch>,
    /// Top credential evidence.
    pub credential_matches: Vec<SemanticMatch>,
    /// Matching summary.
    pub profile_matches: Vec<SemanticMatch>,
    /// Per-group averages and peaks, combined signal, source and mode.
    pub raw: Value,
    /// `local-profile` or `vector-store`.
    pub source: &'static str,
    /// The provider mode used to compare text.
    pub mode: &'static str,
}

/// Scores semantic evidence, defaulting to six skills and three projects.
///
/// Passing no profile allows unscoped matches from the supplied vector snapshot.
#[must_use]
pub fn semantic_fit(
    jd: &str,
    profile: Option<&Value>,
    context: &ScoringContext,
) -> Option<SemanticFit> {
    semantic_fit_with_limits(jd, profile, context, 6, 3)
}

/// Scores semantic evidence with caller-specified skill and project limits.
#[must_use]
pub fn semantic_fit_with_limits(
    jd: &str,
    profile: Option<&Value>,
    context: &ScoringContext,
    top_skills: usize,
    top_projects: usize,
) -> Option<SemanticFit> {
    let limits = [top_skills, top_projects, 3, 3, 1];
    let rows = profile.map(profile_rows::local).unwrap_or_default();
    let local = if rows.is_empty() {
        None
    } else {
        let query = ml::hash_embedding(jd, MINILM_DIMENSIONS);
        let mut matches = Groups::default();
        for row in &rows {
            let vector = ml::hash_embedding(&row.text, MINILM_DIMENSIONS);
            matches.insert(row.kind, &row.label, ml::cosine(&query, &vector));
        }
        matches.finish(limits, "local-profile", EmbeddingMode::Hash)
    };

    let stored = context.vectors.as_deref().and_then(|vectors| {
        if vectors.rows.is_empty() {
            return None;
        }
        let scope = profile.map(profile_rows::allowed_ids);
        stored_fit(
            jd,
            vectors,
            scope.as_ref(),
            context.embedder.as_ref(),
            limits,
        )
    });
    match (local, stored) {
        (local, None) => local,
        (None, stored) => stored,
        (Some(local), Some(stored)) => {
            let degraded = !matches!(stored.mode, "onnx" | "openai" | "sentence-transformer");
            if (degraded && local.score >= stored.score)
                || (stored.score < 45 && local.score >= stored.score + 10)
            {
                Some(local)
            } else {
                Some(stored)
            }
        }
    }
}

fn stored_fit(
    jd: &str,
    vectors: &ProfileVectors,
    scope: Option<&BTreeSet<(VectorKind, String)>>,
    embedder: Option<&Embedder>,
    limits: [usize; 5],
) -> Option<SemanticFit> {
    let rows: Vec<_> = vectors
        .rows
        .iter()
        .filter(|row| {
            row.kind != VectorKind::Profile
                && !row.vector.is_empty()
                && scope.is_none_or(|ids| ids.contains(&(row.kind, row.id.clone())))
        })
        .collect();
    let first = rows.first()?;
    let query = if vectors.mode.is_semantic() {
        let batch = embedder?.embed_with_mode(&[jd]);
        if batch.mode != vectors.mode {
            return None;
        }
        batch.vectors.into_iter().next()?
    } else {
        ml::hash_embedding(jd, first.vector.len())
    };
    let mut groups = Groups::default();
    for row in rows {
        if query.len() != row.vector.len() {
            continue;
        }
        let label = if row.label.is_empty() {
            &row.id
        } else {
            &row.label
        };
        groups.insert(row.kind, label, ml::cosine(&query, &row.vector));
    }
    groups.finish(limits, "vector-store", vectors.mode)
}

#[derive(Default)]
struct Groups([Vec<SemanticMatch>; 5]);

impl Groups {
    fn insert(&mut self, kind: VectorKind, label: &str, similarity: f64) {
        let similarity = similarity.clamp(0.0, 1.0);
        if similarity > 0.01 {
            self.0[kind.index()].push(SemanticMatch {
                label: label.to_owned(),
                similarity,
            });
        }
    }

    fn finish(
        mut self,
        limits: [usize; 5],
        source: &'static str,
        mode: EmbeddingMode,
    ) -> Option<SemanticFit> {
        const WEIGHTS: [f64; 5] = [0.22, 0.34, 0.26, 0.10, 0.08];
        const KEYS: [&str; 5] = [
            "skills",
            "projects",
            "experiences",
            "credentials",
            "profile",
        ];
        let mut weight_sum = 0.0;
        let mut averages = 0.0;
        let mut peaks = 0.0;
        let mut raw = Map::new();
        for kind in VectorKind::ALL {
            let index = kind.index();
            let matches = &mut self.0[index];
            matches.sort_by(|left, right| right.similarity.total_cmp(&left.similarity));
            matches.truncate(limits[index]);
            let mut average = 0.0;
            let mut peak = 0.0;
            if let Some(best) = matches.first() {
                let weight = WEIGHTS[index];
                average =
                    matches.iter().map(|item| item.similarity).sum::<f64>() / matches.len() as f64;
                peak = best.similarity;
                averages += average * weight;
                peaks += peak * weight;
                weight_sum += weight;
            }
            raw.insert(
                format!("{}_avg", KEYS[index]),
                json!(json_fields::rounded(average, 3)),
            );
            raw.insert(
                format!("{}_max", KEYS[index]),
                json!(json_fields::rounded(peak, 3)),
            );
        }
        if weight_sum == 0.0 {
            return None;
        }
        let combined = (0.60 * averages + 0.40 * peaks) / weight_sum;
        let stretch = if source == "local-profile" {
            (combined - 0.06) / 0.30
        } else if mode.is_semantic() {
            (combined - 0.20) / 0.55
        } else {
            (combined - 0.15) / 0.55
        };
        let mode = mode.as_str();
        raw.insert(
            "combined".to_owned(),
            json!(json_fields::rounded(combined, 3)),
        );
        raw.insert("source".to_owned(), json!(source));
        raw.insert("mode".to_owned(), json!(mode));
        let [
            skill_matches,
            project_matches,
            experience_matches,
            credential_matches,
            profile_matches,
        ] = self.0;
        Some(SemanticFit {
            score: ((stretch * 100.0).round_ties_even() as i64).clamp(0, 100),
            skill_matches,
            project_matches,
            experience_matches,
            credential_matches,
            profile_matches,
            raw: Value::Object(raw),
            source,
            mode,
        })
    }
}

impl SemanticFit {
    pub(crate) fn reason(&self) -> String {
        let descriptor = if self.mode.is_empty() {
            self.source.to_owned()
        } else {
            format!("{}, {}", self.source, self.mode)
        };
        let mut reason = format!("embedding similarity vs current profile ({descriptor})");
        let mut sections = Vec::new();
        for (name, matches, limit) in [
            ("projects", &self.project_matches, 2),
            ("experience", &self.experience_matches, 2),
            ("skills", &self.skill_matches, 3),
            ("credentials", &self.credential_matches, 2),
            ("profile", &self.profile_matches, 1),
        ] {
            if !matches.is_empty() {
                let labels: Vec<_> = matches
                    .iter()
                    .take(limit)
                    .map(|item| format!("{} ({:.2})", item.label, item.similarity))
                    .collect();
                sections.push(format!("{name}: {}", labels.join(", ")));
            }
        }
        if !sections.is_empty() {
            reason.push_str(&format!(" - {}", sections.join("; ")));
        }
        if !self.mode.is_empty() && !matches!(self.mode, "onnx" | "openai" | "sentence-transformer")
        {
            reason
                .push_str(" [degraded: local embedding runtime not installed, scores approximate]");
        }
        reason
    }
}

pub(crate) fn field_mismatch(jd: &str, candidate: &str, context: &ScoringContext) -> bool {
    let Some(embedder) = &context.embedder else {
        return false;
    };
    if jd.chars().count() < 40 || candidate.chars().count() < 40 {
        return false;
    }
    let texts = [
        json_fields::clip(candidate, 2000),
        json_fields::clip(jd, 2000),
    ];
    let batch = embedder.embed_with_mode(&texts);
    if !batch.mode.is_semantic() {
        return false;
    }
    let [candidate, job] = batch.vectors.as_slice() else {
        return false;
    };
    ml::cosine(candidate, job) < 0.22
}

#[cfg(test)]
mod tests {
    use std::sync::Arc;

    use agent_hire_ml::{EmbeddingMode, MINILM_DIMENSIONS, hash_embedding};
    use serde_json::json;

    use super::{Groups, ProfileVector, ProfileVectors, ScoringContext, VectorKind, semantic_fit};

    #[test]
    fn semantic_groups_renormalize_weights_and_keep_evidence_order() {
        let mut groups = Groups::default();
        groups.insert(VectorKind::Skill, "low", 0.2);
        groups.insert(VectorKind::Skill, "high", 0.4);
        groups.insert(VectorKind::Project, "project", 0.6);
        groups.insert(VectorKind::Credential, "excluded", 0.01);
        let fit = groups
            .finish([6, 3, 3, 3, 1], "vector-store", EmbeddingMode::Onnx)
            .expect("active groups");
        // (.22*(.6*.30+.4*.40) + .34*.60)/(.22+.34) = .497857...
        assert_eq!(fit.raw["combined"], 0.498);
        assert_eq!(fit.raw["skills_avg"], 0.3);
        assert_eq!(fit.raw["credentials_avg"], 0.0);
        assert_eq!(fit.score, 54);
        assert_eq!(
            fit.reason(),
            "embedding similarity vs current profile (vector-store, onnx) - projects: project (0.60); skills: high (0.40), low (0.20)"
        );
        assert_eq!(
            serde_json::to_value(fit).expect("serialize fit")["skill_matches"],
            json!([["high", 0.4], ["low", 0.2]])
        );
    }

    #[test]
    fn stored_rows_are_scoped_by_kind_and_id() {
        let vector = hash_embedding("backend applications", MINILM_DIMENSIONS);
        let context = ScoringContext {
            embedder: None,
            vectors: Some(Arc::new(ProfileVectors {
                mode: EmbeddingMode::Hash,
                rows: vec![
                    ProfileVector {
                        kind: VectorKind::Project,
                        id: "row".to_owned(),
                        label: "Other table".to_owned(),
                        vector: vector.clone(),
                    },
                    ProfileVector {
                        kind: VectorKind::Skill,
                        id: "row".to_owned(),
                        label: "Allowed".to_owned(),
                        vector,
                    },
                ],
            })),
        };
        let profile = json!({"skills":[{"id":"row"}]});
        let fit = semantic_fit("backend applications", Some(&profile), &context)
            .expect("stored skill matches");
        assert_eq!(fit.source, "vector-store");
        assert_eq!(fit.score, 100);
        assert_eq!(fit.skill_matches[0].label, "Allowed");
        assert!(fit.project_matches.is_empty());
        assert!(semantic_fit("backend applications", Some(&json!({})), &context).is_none());
        assert_eq!(
            semantic_fit("backend applications", None, &context)
                .expect("unscoped")
                .project_matches
                .len(),
            1
        );
    }
}
